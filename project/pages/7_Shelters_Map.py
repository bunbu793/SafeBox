#### ① まず身を守る
- 机の下に入る  
- 頭を守る  
- 揺れが収まるまで動かない  

#### ② 揺れが止まったら
- 火の始末  
- 家族の安否確認  
- 避難情報を確認  

#### ③ 備蓄
- 水・食料  
- 懐中電灯  
- モバイルバッテリー  
""",

    "津波": """
### 🌊 津波のときはこう動く

- すぐに高台へ避難  
- 海岸から離れる  
- 車より徒歩  
- 警報解除まで戻らない  
""",

    "台風": """
### 🌀 台風のときはこう動く

